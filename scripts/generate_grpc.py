"""Regenerate the gRPC stubs from proto/ into the backend package.

Usage: python scripts/generate_grpc.py
CI runs this and fails if the committed stubs differ.
"""

import re
import shutil
import sys
from pathlib import Path

from grpc_tools import protoc

ROOT = Path(__file__).resolve().parents[1]
PROTO_ROOT = ROOT / "proto"
PROTO_FILE = PROTO_ROOT / "sobracero" / "analysis" / "v1" / "rescue_analysis.proto"
OUTPUT = ROOT / "app-backend" / "app" / "infrastructure" / "analysis" / "generated"
HEADER = "# Generated by scripts/generate_grpc.py. Do not edit.\n# flake8: noqa\n# isort: skip_file\n# fmt: off\n"


def main() -> int:
    OUTPUT.mkdir(parents=True, exist_ok=True)
    result = protoc.main(
        [
            "protoc",
            f"-I{PROTO_ROOT}",
            f"--python_out={OUTPUT}",
            f"--grpc_python_out={OUTPUT}",
            f"--pyi_out={OUTPUT}",
            str(PROTO_FILE),
        ]
    )
    if result != 0:
        return result
    generated = OUTPUT / "sobracero" / "analysis" / "v1"
    for source in generated.glob("*.py*"):
        target = OUTPUT / source.name
        text = source.read_text(encoding="utf-8")
        text = re.sub(r"from sobracero\.analysis\.v1 import (\w+) as", r"from . import \1 as", text)
        target.write_text(HEADER + text, encoding="utf-8", newline="\n")
    shutil.rmtree(OUTPUT / "sobracero")
    (OUTPUT / "__init__.py").write_text("", encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
